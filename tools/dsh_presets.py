#!/usr/bin/env python3
"""Генератор DSH-пресетов ролей и wrapper-скриптов запуска.

DSH не обнаруживает проектные пресеты: они объявляются в композиции профиля.
Модуль собирает project-local патч `.dsh/presets.patch.yml` из шаблонов,
снятых с `presets/standard.patch.yml` установленного DSH.

Использование:
  python tools/dsh_presets.py render --project-dir .
  python tools/dsh_presets.py check  --project-dir .
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Optional

from dsh_rules import FRONTMATTER_RE, _strip_terminal_backmatter

ROLES = [
    "analyst",
    "architect",
    "debugger",
    "developer-code",
    "developer-tests",
    "explorer",
    "reviewer",
    "scenario-author",
    "scenario-coder",
    "tester",
]
LEAD_ID = "1c-lead"
ROLE_PREFIX = "1c-"
TEMPLATE_LEAD = Path(__file__).resolve().parent / "dsh-presets-lead.yml.tmpl"
TEMPLATE_ROLE = Path(__file__).resolve().parent / "dsh-presets-role.yml.tmpl"
PERSONA_INDENT = " " * 16


def role_id(role: str) -> str:
    return f"{ROLE_PREFIX}{role}"


def _template_hashes() -> dict[str, str]:
    return {
        "lead": hashlib.sha256(TEMPLATE_LEAD.read_bytes()).hexdigest(),
        "role": hashlib.sha256(TEMPLATE_ROLE.read_bytes()).hexdigest(),
    }


def _dsh_version() -> str:
    try:
        cmd = ["dsh.cmd", "--version"] if sys.platform == "win32" else ["dsh", "--version"]
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
        out = (proc.stdout or proc.stderr or "").strip().splitlines()
        return out[0].strip() if out else "unknown"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def read_role_body(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(text)
    body = text[match.end():] if match else text
    body = _strip_terminal_backmatter(body).strip()
    if not body:
        raise ValueError(f"empty role body: {path}")
    return body


def _persona_block(body: str) -> str:
    lines = body.splitlines() or [""]
    return "\n".join((PERSONA_INDENT + line).rstrip() if line.strip() else "" for line in lines)


def _render_row(template: str, preset_id: str, order: int, persona: str, allowed: str = "") -> str:
    text = template.replace("{{PRESET_ID}}", preset_id)
    text = text.replace("{{ORDER}}", str(order))
    text = text.replace("{{ALLOWED_PRESETS}}", allowed)
    text = text.replace("{{PERSONA_PREFIX}}", _persona_block(persona))
    return text.rstrip() + "\n"


def render_presets(
    project_dir: Path,
    framework_dir: Path,
    mirror_dir: Optional[Path] = None,
    lang: str = "en",
    include_roles: Optional[list[str]] = None,
    keep_default: bool = False,
) -> dict:
    """Пишет .dsh/presets.patch.yml и wrapper; возвращает фрагмент манифеста."""
    base = framework_dir
    if lang != "ru" and mirror_dir and mirror_dir.is_dir():
        base = mirror_dir
    subagents = base / "subagents"
    roles = include_roles or list(ROLES)
    missing = [role for role in roles if not (subagents / f"{role}.md").exists()]
    if missing:
        raise FileNotFoundError(f"role files not found in {subagents}: {', '.join(missing)}")

    lead_body = read_role_body(subagents / "orchestrator.md")
    allowed = ", ".join(role_id(role) for role in roles)
    rows: list[str] = [
        _render_row(TEMPLATE_LEAD.read_text(encoding="utf-8"), LEAD_ID, 10, lead_body, allowed)
    ]
    for idx, role in enumerate(roles, start=1):
        body = read_role_body(subagents / f"{role}.md")
        rows.append(_render_row(TEMPLATE_ROLE.read_text(encoding="utf-8"), role_id(role), 10 + idx, body))

    lines = [
        "# Generated by tools/dsh_presets.py. Do not edit; run the installer to regenerate.",
        "- insert:",
    ]
    for row in rows:
        lines.append(row.rstrip())
    if not keep_default:
        lines.extend([
            "- id: agent-preset-registry",
            "  config:",
            f"    default: {LEAD_ID}",
        ])
    patch = "\n".join(lines).rstrip() + "\n"

    presets_file = project_dir / ".dsh" / "presets.patch.yml"
    presets_file.parent.mkdir(parents=True, exist_ok=True)
    presets_file.write_text(patch, encoding="utf-8")

    _write_launcher(project_dir / "dsh-1c.sh", "sh")
    _write_launcher(project_dir / "dsh-1c.ps1", "ps1")

    return {
        "file": ".dsh/presets.patch.yml",
        "dsh_version": _dsh_version(),
        "template_sha256": _template_hashes(),
        "roles": [role_id(role) for role in roles],
        "lead": LEAD_ID,
        "default_preset": None if keep_default else LEAD_ID,
    }


def _write_launcher(path: Path, kind: str) -> None:
    if kind == "sh":
        content = """#!/bin/sh
# Generated by tools/dsh_presets.py.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
exec dsh web --patch "$ROOT/.dsh/presets.patch.yml" "$@"
"""
    else:
        content = """# Generated by tools/dsh_presets.py.
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
& dsh web --patch (Join-Path $Root '.dsh/presets.patch.yml') @args
exit $LASTEXITCODE
"""
    path.write_text(content, encoding="utf-8")
    if kind == "sh":
        try:
            path.chmod(0o755)
        except OSError:
            pass


def _manifest_presets(project_dir: Path) -> dict:
    path = project_dir / ".dsh" / "manifest.json"
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    return dict((data.get("dsh") or {}).get("presets") or {})


def check_presets(project_dir: Path) -> tuple[bool, list[str]]:
    errors: list[str] = []
    presets_file = project_dir / ".dsh" / "presets.patch.yml"
    if not presets_file.exists():
        return False, ["missing .dsh/presets.patch.yml"]
    text = presets_file.read_text(encoding="utf-8")
    if f"id: {LEAD_ID}" not in text:
        errors.append(f"presets patch does not declare {LEAD_ID}")
    manifest = _manifest_presets(project_dir)
    declared_roles = manifest.get("roles") or [role_id(role) for role in ROLES]
    for rid in declared_roles:
        if f"id: {rid}" not in text:
            errors.append(f"presets patch does not declare {rid}")
    if "{{" in text:
        errors.append("presets patch still contains template placeholders")
    if manifest:
        current = _template_hashes()
        stored = manifest.get("template_sha256") or {}
        for key, sha in current.items():
            if stored.get(key) != sha:
                errors.append(f"preset template '{key}' changed since install")
        stored_version = manifest.get("dsh_version")
        current_version = _dsh_version()
        if stored_version and current_version != "unknown" and stored_version != current_version:
            errors.append(
                f"DSH version changed since install: {stored_version} -> {current_version}; regenerate presets"
            )
    return (not errors), errors


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="DSH preset generator")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("render", "check"):
        p = sub.add_parser(name)
        p.add_argument("--project-dir", type=Path, default=Path("."))
        p.add_argument("--framework-dir", type=Path, default=Path("framework"))
        p.add_argument("--mirror-dir", type=Path, default=Path("framework_eng"))
        p.add_argument("--lang", choices=("en", "ru"), default="en")
        if name == "render":
            p.add_argument("--keep-default", action="store_true")
    args = parser.parse_args(argv)
    project_dir = args.project_dir.resolve()

    if args.command == "check":
        ok, errors = check_presets(project_dir)
        for err in errors:
            print(err, file=sys.stderr)
        print("OK" if ok else "FAILED")
        return 0 if ok else 1

    data = render_presets(
        project_dir,
        args.framework_dir.resolve(),
        args.mirror_dir.resolve() if args.mirror_dir else None,
        args.lang,
        keep_default=args.keep_default,
    )
    print(f"rendered {len(data['roles']) + 1} preset(s) -> {data['file']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
